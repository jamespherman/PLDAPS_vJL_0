#!/usr/bin/env python3
"""Generators for the PLDAPS_vK2 wiki (stdlib only).

Usage:  python3 wiki/_tools/wiki_gen.py <command> [args]

  index            regenerate wiki/index.md from page frontmatter
  facts            regenerate <!-- GEN:facts --> blocks on pages with `task_dir:`
  strobes          regenerate wiki/reference/strobe-codes.md from +pds/initCodes.m
  all              index + facts + strobes
  stamp PAGE...    record current source hashes (+ verified_at, updated) on pages;
                   PAGE is a wiki-relative path, or `--all`
  stale [--brief]  list pages whose sources changed since they were stamped

Generated content is overwritten on every run; never hand-edit it.
"""
import datetime
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import wiki_lib as wl  # noqa: E402

TODAY = datetime.date.today().isoformat()
GEN_START, GEN_END = "<!-- GEN:facts:start -->", "<!-- GEN:facts:end -->"


# ---------------------------------------------------------------- MATLAB parsing
def read(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        return fh.read()


def strip_comment(line):
    """Drop a trailing MATLAB % comment, ignoring % inside single-quoted strings."""
    out, in_str = [], False
    for i, ch in enumerate(line):
        if ch == "'":
            prev = line[i - 1] if i else " "
            if in_str or not (prev.isalnum() or prev in ")]}_.'"):
                in_str = not in_str
        if ch == "%" and not in_str:
            break
        out.append(ch)
    return "".join(out)


def parse_states(text):
    return [(m.group(1), int(m.group(2))) for m in
            re.finditer(r"^\s*p\.state\.(\w+)\s*=\s*(\d+)\s*;", text, re.M)]


def parse_strobe_list(text):
    """[(codeName, valueExpr)] from `p.init.strobeList = {...};` (or the older
    `fliplr({ 'expr', 'name'; ... })` form), or None if absent."""
    m = re.search(r"^\s*p\.init\.strobeList\s*=\s*(fliplr\s*\(\s*)?\{", text, re.M)
    if not m:
        return None
    flipped = bool(m.group(1))
    entries = []
    for raw in text[m.end():].splitlines():
        line = strip_comment(raw).strip()
        if line.startswith("}"):
            break
        e = re.match(r"^'((?:[^']|'')*)'\s*,?\s*'((?:[^']|'')*)'\s*[;,]?\s*(\.\.\.)?\s*(\}\s*\)?\s*;)?\s*$", line)
        if e:
            first, second = (g.replace("''", "'") for g in e.group(1, 2))
            name, expr = (second, first) if flipped else (first, second)
            entries.append((name, expr))
        if re.search(r"\}\s*\)?\s*;\s*$", line):
            break
    return entries


def parse_codes(text):
    """[(section, name, value, comment)] from initCodes.m."""
    out, section = [], ""
    for raw in text.splitlines():
        if raw.startswith("%%"):
            section = raw.lstrip("%").strip() or section
            continue
        m = re.match(r"^\s*codes\.(\w+)\s*=\s*(\d+)\s*;\s*(?:%\s*(.*))?$", raw)
        if m:
            out.append((section, m.group(1), int(m.group(2)), (m.group(3) or "").strip()))
    return out


def task_files(task_dir_abs):
    """Top-level .m files of a task dir, conflict copies and .asv excluded."""
    return sorted(f for f in os.listdir(task_dir_abs)
                  if f.endswith(".m") and not wl.is_conflict_copy(f))


def primary_settings(files):
    runs = [f for f in files if f.endswith("_run.m")]
    if runs:
        cand = runs[0][:-len("_run.m")] + "_settings.m"
        if cand in files:
            return cand
    settings = [f for f in files if "_settings" in f]
    return settings[0] if settings else None


def walk_m(path):
    for root, dirs, files in os.walk(path):
        dirs[:] = sorted(d for d in dirs if d in ("supportFunctions", "actions") or root != path)
        for f in sorted(files):
            if f.endswith(".m") and not wl.is_conflict_copy(f):
                yield os.path.join(root, f)


# ---------------------------------------------------------------- facts blocks
def last_touched(rel_dir):
    out = wl.git("log", "-1", "--format=%ad %h", "--date=short", "--", rel_dir)
    return out.strip() or "untracked"


def facts_block(task_dir):
    rel = task_dir.rstrip("/") + "/"
    absd = os.path.join(wl.REPO_DIR, rel)
    files = task_files(absd)
    settings = [f for f in files if "_settings" in f]
    prim = primary_settings(files)
    lines = [GEN_START,
             "<!-- Generated by wiki/_tools/wiki_gen.py facts. Do not edit by hand. -->",
             "", "### Generated facts", "",
             f"- **Directory:** `{rel}` — last commit touching it: {last_touched(rel)}"]
    quintet = [f for f in files if re.search(r"_(init|next|run|finish)\.m$", f)]
    lines.append(f"- **Quintet files:** {', '.join(f'`{f}`' for f in quintet) or 'none at top level'}")
    lines.append(f"- **Settings files ({len(settings)}):** "
                 + (", ".join(f"`{f}`" + (" (primary)" if f == prim else "") for f in settings) or "none"))
    sub = []
    for d in ("supportFunctions", "actions"):
        p = os.path.join(absd, d)
        if os.path.isdir(p):
            n = sum(1 for _ in walk_m(p))
            sub.append(f"`{d}/` ({n} .m files)")
    others = sorted(d + "/" for d in os.listdir(absd)
                    if os.path.isdir(os.path.join(absd, d)) and d not in ("supportFunctions", "actions"))
    if sub:
        lines.append(f"- **Subfolders:** {', '.join(sub)}"
                     + (f"; other: {', '.join(f'`{o}`' for o in others)}" if others else ""))
    elif others:
        lines.append(f"- **Subfolders:** {', '.join(f'`{o}`' for o in others)}")

    if prim:
        text = read(os.path.join(absd, prim))
        m = re.search(r"p\.init\.taskCode\s*=\s*p\.init\.codes\.(\w+)", text) or \
            re.search(r"codes\.(uniqueTaskCode_\w+)", text)
        if m:
            lines.append(f"- **Unique task code:** `{m.group(1)}`")
        states = parse_states(text)
        if states:
            lines.append(f"- **States** (`p.state`, from `{prim}`): "
                         + ", ".join(f"`{n}`={v}" for n, v in states))
        sl = parse_strobe_list(text)
        if sl:
            lines += ["", f"**strobeList** (from `{prim}`; strobed each trial by `pds.strobeTrialData`):", "",
                      "| code name | value expression |", "|---|---|"]
            for name, expr in sl:
                expr_md = expr.replace("|", "\\|")
                if len(expr_md) > 110:
                    expr_md = expr_md[:107] + "…"
                lines.append(f"| `{name}` | `{expr_md}` |")
            base = {n for n, _ in sl}
            for f in settings:
                if f == prim:
                    continue
                other = parse_strobe_list(read(os.path.join(absd, f)))
                if other is None:
                    continue
                names = {n for n, _ in other}
                extra, missing = sorted(names - base), sorted(base - names)
                if extra or missing:
                    lines.append(f"\n- `{f}` strobeList differs: "
                                 + (f"adds {', '.join(f'`{x}`' for x in extra)}" if extra else "")
                                 + ("; " if extra and missing else "")
                                 + (f"lacks {', '.join(f'`{x}`' for x in missing)}" if missing else ""))
        elif sl is None:
            lines.append("- **strobeList:** none defined in primary settings file")
    lines += ["", GEN_END]
    return "\n".join(lines)


def cmd_facts():
    n = 0
    for rel, pg in wl.load_pages().items():
        td = (pg["meta"] or {}).get("task_dir")
        if not td or not isinstance(td, str):
            continue
        if not os.path.isdir(os.path.join(wl.REPO_DIR, td)):
            print(f"facts: {rel}: task_dir {td} not found")
            continue
        block = facts_block(td)
        text = pg["text"]
        if GEN_START in text and GEN_END in text:
            pre, rest = text.split(GEN_START, 1)
            post = rest.split(GEN_END, 1)[1]
            new = pre + block + post
        else:
            new = text.rstrip("\n") + "\n\n" + block + "\n"
        if new != text:
            with open(pg["abs"], "w", encoding="utf-8") as fh:
                fh.write(new)
            n += 1
    print(f"facts: updated {n} page(s)")


# ---------------------------------------------------------------- strobe registry
def task_code_usage():
    """{taskDir: (strobeListNames:set, referencedCodes:set)} across all tasks, plus +pds."""
    usage = {}
    for d in sorted(os.listdir(os.path.join(wl.REPO_DIR, "tasks"))):
        absd = os.path.join(wl.REPO_DIR, "tasks", d)
        if not os.path.isdir(absd):
            continue
        listed, refd = set(), set()
        for f in task_files(absd):
            text = read(os.path.join(absd, f))
            sl = parse_strobe_list(text) or []
            listed |= {n for n, _ in sl}
            refd |= set(re.findall(r"codes\.(\w+)", text))
        for sub in ("supportFunctions", "actions"):
            for fp in walk_m(os.path.join(absd, sub)) if os.path.isdir(os.path.join(absd, sub)) else []:
                refd |= set(re.findall(r"codes\.(\w+)", read(fp)))
        usage[d] = (listed, refd)
    refd = set()
    for pkg in ("+pds", "+pdsActions"):
        for f in os.listdir(os.path.join(wl.REPO_DIR, pkg)):
            if f.endswith(".m") and f != "initCodes.m" and not wl.is_conflict_copy(f):
                refd |= set(re.findall(r"codes\.(\w+)", read(os.path.join(wl.REPO_DIR, pkg, f))))
    usage["+pds"] = (set(), refd)
    return usage


def cmd_strobes():
    codes = parse_codes(read(os.path.join(wl.REPO_DIR, "+pds", "initCodes.m")))
    usage = task_code_usage()
    names = {c[1] for c in codes}
    by_value = {}
    for _, name, val, _ in codes:
        by_value.setdefault(val, []).append(name)
    dups = {v: n for v, n in by_value.items() if len(n) > 1}
    dup_names = {n for v in dups.values() for n in v}
    defined_twice = sorted({n for n in names if sum(1 for c in codes if c[1] == n) > 1})

    lines = ["---", "title: Strobe code registry", "type: reference", "category: Reference",
             "summary: GENERATED table of every code in +pds/initCodes.m, which tasks use it, and integrity checks",
             "sources:", f"  - +pds/initCodes.m @ {wl.source_hash('+pds/initCodes.m')}",
             f"verified_at: {wl.git('rev-parse', '--short', 'HEAD').strip()}", f"updated: {TODAY}", "---", "",
             "# Strobe code registry", "",
             "<!-- Generated by wiki/_tools/wiki_gen.py strobes. Do not edit by hand. -->", "",
             "Generated from `+pds/initCodes.m` (the HOLY file — see [strobe codes](../concepts/strobe-codes.md)) "
             "and a scan of every task directory. *Used by* lists tasks whose strobeList names the code "
             "(**bold**) or whose code references `codes.<name>` (plain). `+pds` means a shared library "
             "function references it.", "",
             "## Integrity checks", ""]
    lines.append(f"- {len(codes)} code definitions, {len(by_value)} distinct values.")
    lines.append("- Duplicate values: " + ("none." if not dups else
                 "; ".join(f"{v}: {', '.join(n)}" for v, n in sorted(dups.items()))))
    lines.append("- Names assigned more than once: " + (", ".join(f"`{n}`" for n in defined_twice) or "none."))
    unknown = []
    for d, (listed, refd) in usage.items():
        for n in sorted(listed - names):
            unknown.append(f"`{n}` (strobeList in tasks/{d})")
    lines.append("- strobeList names with no initCodes entry (`pds.strobeTrialData` wraps its whole loop in one try/catch, so such a row and every row after it in that list go unstrobed): "
                 + (", ".join(unknown) if unknown else "none."))
    lines += ["", "## Codes", ""]
    section = None
    for sec, name, val, comment in codes:
        if sec != section:
            section = sec
            lines += ["", f"### {sec}", "", "| code | value | used by | note |", "|---|---|---|---|"]
        users = []
        for d, (listed, refd) in usage.items():
            if name in listed:
                users.append(f"**{d}**")
            elif name in refd:
                users.append(d)
        flag = " ⚠ duplicate value" if name in dup_names else ""
        note = comment.replace("|", "\\|")
        lines.append(f"| `{name}` | {val}{flag} | {', '.join(users) or '—'} | {note} |")
    out = os.path.join(wl.WIKI_DIR, "reference", "strobe-codes.md")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"strobes: {len(codes)} codes, {len(dups)} duplicate value(s), {len(unknown)} unknown strobeList name(s)")


# ---------------------------------------------------------------- index
CATEGORY_ORDER = ["Start here", "Concepts", "Library", "Reference", "Tasks", "Catalogs", "Analyses"]


def cmd_index():
    pages = wl.load_pages()
    groups = {}
    for rel, pg in pages.items():
        if rel in ("index.md", "log.md"):
            continue
        meta = pg["meta"] or {}
        cat = meta.get("category") or "Uncategorized"
        title = meta.get("title") or rel
        summary = meta.get("summary") or ""
        status = meta.get("status")
        tag = f" `{status}`" if isinstance(status, str) and status else ""
        groups.setdefault(cat, []).append((str(title).lower(), f"- [{title}]({rel}){tag} — {summary}".rstrip(" —")))

    def key(cat):
        for i, prefix in enumerate(CATEGORY_ORDER):
            if cat.startswith(prefix):
                return (i, cat)
        return (len(CATEGORY_ORDER), cat)

    lines = ["---", "title: Index", "type: meta", "category: Start here",
             "summary: Catalog of every wiki page (generated)", "sources: []",
             "verified_at: n/a", f"updated: {TODAY}", "---", "",
             "# PLDAPS_vK2 wiki — index", "",
             "<!-- Generated by wiki/_tools/wiki_gen.py index from page frontmatter. Do not edit by hand. -->", "",
             "Read this first when answering a question, then drill into pages. "
             "Conventions: [SCHEMA](SCHEMA.md). History of wiki edits: [log](log.md).", ""]
    for cat in sorted(groups, key=key):
        lines += [f"## {cat}", ""] + [e for _, e in sorted(groups[cat])] + [""]
    with open(os.path.join(wl.WIKI_DIR, "index.md"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print(f"index: {sum(len(v) for v in groups.values())} page(s)")


# ---------------------------------------------------------------- stamp / stale
def stamp_page(abspath):
    text = read(abspath)
    if not text.startswith("---"):
        return False
    end = text.find("\n---", 3)
    head, body = text[:end], text[end:]
    out, in_sources = [], False
    for line in head.split("\n"):
        if re.match(r"^sources:\s*$", line):
            in_sources = True
            out.append(line)
            continue
        if in_sources:
            m = re.match(r"^(\s*-\s+)(.*)$", line)
            if m:
                path, _ = wl.split_source(m.group(2).split(" #")[0])
                h = wl.source_hash(path)
                out.append(f"{m.group(1)}{path} @ {h}" if h else f"{m.group(1)}{path}")
                continue
            in_sources = False
        if line.startswith("verified_at:"):
            line = f"verified_at: {wl.git('rev-parse', '--short', 'HEAD').strip() or 'n/a'}"
        elif line.startswith("updated:"):
            line = f"updated: {TODAY}"
        out.append(line)
    new = "\n".join(out) + body
    if new != text:
        with open(abspath, "w", encoding="utf-8") as fh:
            fh.write(new)
    return True


def cmd_stamp(args):
    pages = wl.load_pages()
    targets = list(pages) if args == ["--all"] else args
    for t in targets:
        t = t[len("wiki/"):] if t.startswith("wiki/") else t
        if t not in pages:
            print(f"stamp: no such page {t}")
            continue
        stamp_page(pages[t]["abs"])
    print(f"stamp: {len(targets)} page(s)")


def cmd_stale(args):
    stale = wl.stale_pages()
    if "--brief" in args:
        print(", ".join(sorted(stale)))
        return
    for rel, paths in sorted(stale.items()):
        print(f"{rel}: {', '.join(paths)}")
    print(f"{len(stale)} stale page(s)")


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    cmd, args = sys.argv[1], sys.argv[2:]
    if cmd in ("strobes", "all"):
        cmd_strobes()
    if cmd in ("facts", "all"):
        cmd_facts()
    if cmd in ("index", "all"):
        cmd_index()
    if cmd == "stamp":
        cmd_stamp(args)
    elif cmd == "stale":
        cmd_stale(args)
    elif cmd not in ("index", "facts", "strobes", "all"):
        print(__doc__)


if __name__ == "__main__":
    main()
